"""Run the simulation study and write its results and report.

    uv run python -m scripts.run_research           # rewrite results + report
    uv run python -m scripts.run_research --check   # fail if either is stale

Writes ``web/src/data/research.json`` (read by the dashboard's Backtest page) and
``docs/research/simulation-study.md`` (a pure function of that JSON). The check compares
numbers with a tolerance: floating-point results can differ in the last bits between
platforms, and that is not a change in the research.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

from alphadots_research.study import STRATEGIES, run

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "web" / "src" / "data" / "research.json"
REPORT = ROOT / "docs" / "research" / "simulation-study.md"
REL_TOL = 1e-6
ABS_TOL = 1e-9


def _clean(value: Any) -> Any:
    """Round floats for a stable, readable file; NaN becomes null (JSON has no NaN)."""
    if isinstance(value, float):
        return None if not math.isfinite(value) else round(value, 6)
    if isinstance(value, dict):
        return {key: _clean(item) for key, item in value.items()}
    if isinstance(value, list | tuple):
        return [_clean(item) for item in value]
    return value


def _close(a: Any, b: Any, path: str = "") -> list[str]:
    if isinstance(a, dict) and isinstance(b, dict):
        if a.keys() != b.keys():
            return [f"{path}: keys differ"]
        return [problem for key in a for problem in _close(a[key], b[key], f"{path}.{key}")]
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return [f"{path}: length {len(a)} != {len(b)}"]
        return [
            problem
            for i, (x, y) in enumerate(zip(a, b, strict=True))
            for problem in _close(x, y, f"{path}[{i}]")
        ]
    if isinstance(a, float | int) and isinstance(b, float | int) and not isinstance(a, bool):
        return (
            [] if math.isclose(a, b, rel_tol=REL_TOL, abs_tol=ABS_TOL) else [f"{path}: {a} != {b}"]
        )
    return [] if a == b else [f"{path}: {a!r} != {b!r}"]


def _num(value: float | None, digits: int = 2, *, signed: bool = True, pct: bool = False) -> str:
    if value is None:
        return "n/a"
    shown = value * 100 if pct else value
    text = f"{shown:+.{digits}f}" if signed else f"{shown:.{digits}f}"
    return text.replace("-", "\N{MINUS SIGN}") + ("%" if pct else "")


def report(results: dict[str, Any]) -> str:
    """The paper-style write-up, generated entirely from the results."""
    cfg = results["config"]
    market = cfg["market"]
    planted, null = results["worlds"]["planted"], results["worlds"]["null"]
    ps, ns = planted["strategies"], null["strategies"]
    pit = results["pit_guard"]

    def table(world: dict[str, Any], period: str) -> str:
        rows = [
            "| Strategy | Mean rank IC | IC t-stat | Net Sharpe [95% CI] | Gross Sharpe "
            "| Max drawdown | Traded per day |",
            "|---|---:|---:|---|---:|---:|---:|",
        ]
        for key in STRATEGIES:
            s = world["strategies"][key][period]
            rows.append(
                f"| {world['strategies'][key]['label']} | {_num(s['mean_ic'], 3)} | "
                f"{_num(s['ic_tstat'], 1)} | "
                f"{_num(s['sharpe'])} [{_num(s['sharpe_ci_low'])}, {_num(s['sharpe_ci_high'])}] | "
                f"{_num(s['gross_sharpe'])} | {_num(s['max_drawdown'], 1, pct=True)} | "
                f"{_num(s['turnover'], 2, signed=False)} |"
            )
        return "\n".join(rows)

    sp, sn = ps["sentiment"]["oos"], ns["sentiment"]["oos"]
    detected = sp["ic_tstat"] is not None and sp["ic_tstat"] > 3
    silent = sn["ic_tstat"] is not None and abs(sn["ic_tstat"]) < 2
    costs = ", ".join(
        f"{_num(row['sharpe'])} at {row['bps']:g} bps" for row in planted["cost_sensitivity"]
    )
    folds = "\n".join(
        f"| {f['index'] + 1} | {f['train_start']} to {f['train_end']} | "
        f"{f['test_start']} to {f['test_end']} | "
        f"{f['tau_days']:g} | {_num(f['train_ic'], 3)} | {_num(f['test_ic'], 3)} |"
        for f in planted["folds"]
    )
    tau_grid = ", ".join(f"{t:g}" for t in cfg["tau_grid_days"])
    dsr = planted["deflated_sharpe"]
    dsr_probability = _num(dsr["probability"], 2, signed=False)
    turnover_pct = _num(sp["turnover"] * 100, 0, signed=False)
    detected_note = "" if detected else ' (Below the t > 3 bar this study sets for "detected".)'
    silent_note = ", indistinguishable from zero" if silent else ""
    return f"""# Simulation study: does the decayed-sentiment signal predict returns?

*Generated by `scripts/run_research.py` from `web/src/data/research.json`. Every number
below comes from running the code; nothing is typed in by hand. This is a study of a
**synthetic** market, built to grade the method. It says nothing about real markets.*

## Question

AlphaDots turns news into a decayed sentiment score per issuer,
`S(i,t) = sum_j relevance * materiality * sentiment_j * exp(-age_j / tau)`. Two things
have to be true before such a score is worth anything: the evaluation must be able to
**find** a real effect, and it must **not invent** one. Real data cannot test either,
because the true answer is unknown. A simulation where the answer is chosen in advance can.

## Data

A synthetic market of {market["n_assets"]} assets over {market["n_days"]} trading days
(from {market["start"]}), seed {market["seed"]}. News arrives at {market["news_rate"]}
items per asset per day: {results["news"]["items"]} items, of which the sentiment model
read {results["news"]["readings"]} and abstained on {results["news"]["abstained"]}. Each
item has a latent tone. The model sees it only through a noisy reading (correlation
{market["reading_quality"]}), the way a lexicon or FinBERT score would.

Tone moves prices in two ways. A **same-day reaction** ({market["reaction"]} daily
volatilities per unit of tone x materiality) is priced into the close right after
publication, before any honest strategy can act on it. A **post-availability drift**
({market["drift"]} daily volatilities, decaying with a {market["drift_tau_days"]}-day time
constant) follows over the next days: this is the planted, tradable effect. The **null
world** is identical, with the drift set to zero.

## Method

- **Signal.** Computed with `alphadots_quant.decayed_sentiment`, the same function the
  live signal engine runs. Each call is deliberately handed readings from up to a day
  *after* its decision time; the function's own point-in-time guard refused them
  ({pit["offered_before_available"]} times for the {cfg["lookahead_tau_days"]:g}-day panel).
- **Portfolio.** Each close, long the top 30% and short the bottom 30% of names with
  recent news (equal weight, gross exposure 1). Days with fewer than {cfg["min_names"]}
  such names are not traded. Positions are held one day.
- **Costs.** {cfg["cost_bps"]:g} bps of every dollar traded (buys and sells), charged every day.
- **Validation.** Expanding-window walk-forward: first training window
  {cfg["first_train_days"]} days, then {cfg["folds"]} test blocks of up to
  {cfg["test_days"]} days. A gap of {cfg["purge_days"]} day (purge, the label horizon) plus
  {cfg["embargo_days"]} days (embargo) separates training from testing. The decay constant
  `tau` is chosen on each training window only, from {tau_grid} days.
  The last {cfg["holdout_days"]} days are an untouched holdout, evaluated once.
- **Uncertainty.** Sharpe 95% intervals from a stationary block bootstrap (mean block
  10 days, 1,000 resamples). A deflated Sharpe ratio accounts for the {dsr["trials"]}
  values of `tau` that were tried.
- **Controls.** Shuffled sentiment (scores reassigned among names each day), the signal
  acted on {cfg["lag_days"]} days late, a price-only momentum baseline
  ({cfg["momentum_days"]} days), and a **look-ahead bug** (the signal computed as of the
  next close), included on purpose.

## Results: planted world

Out of sample (walk-forward test blocks):

{table(planted, "oos")}

Untouched holdout ({cfg["holdout_days"]} days, `tau` = {planted["holdout_tau_days"]:g} days):

{table(planted, "holdout")}

Mean next-day return by signal quintile (out of sample, lowest to highest):
{", ".join(_num(v, 1) for v in planted["quintiles_bps"])} bps.

Net Sharpe of the news signal at different costs: {costs}.

Deflated Sharpe: the best of {dsr["trials"]} tries would show an
annualised Sharpe of {_num(dsr["benchmark_annualized"])} by luck;
the probability that the true Sharpe beats that is
{dsr_probability}.

Walk-forward folds:

| Fold | Train | Test | tau (days) | Train IC | Test IC |
|---:|---|---|---:|---:|---:|
{folds}

## Results: null world

{table(null, "oos")}

## What was learned

1. **The method finds a real effect.** In the planted world the news signal's
   out-of-sample rank IC is {_num(sp["mean_ic"], 3)} (t = {_num(sp["ic_tstat"], 1)}), and
   the holdout agrees ({_num(ps["sentiment"]["holdout"]["mean_ic"], 3)}).{detected_note}
2. **It does not invent one.** In the null world the same procedure gives an IC of
   {_num(sn["mean_ic"], 3)} (t = {_num(sn["ic_tstat"], 1)}){silent_note}.
   The shuffled and lagged controls are near zero in both worlds.
3. **A look-ahead bug would have looked like a great strategy.** Computing the signal
   as of the next close (that is, with information from after the decision) earns a net
   Sharpe of {_num(ns["lookahead"]["oos"]["sharpe"])} *in the world with nothing to find*.
   The honest pipeline earns {_num(sn["sharpe"])} there. This is the single most important
   number in the study: it is the size of the error the point-in-time guard prevents.
4. **A real signal is not yet a profitable one.** Gross of costs the news signal's
   Sharpe is {_num(sp["gross_sharpe"])}; after {cfg["cost_bps"]:g} bps it is
   {_num(sp["sharpe"])}, with a 95% interval of [{_num(sp["sharpe_ci_low"])},
   {_num(sp["sharpe_ci_high"])}]. Rebalancing daily trades about
   {turnover_pct}% of gross exposure every day, and costs take most of the edge.
   The deflated Sharpe probability of {dsr_probability}
   says the evidence would not survive the number of things tried.

## Is this enough to justify more work?

On the method: yes. The evaluation separates a real effect from none, and catches a leak
that would otherwise pass as alpha. On the strategy: not as built. The next steps it
points to are lowering turnover (holding positions longer, trading only on larger signal
changes) and testing on real, licensed data, where the effect size is unknown and could
be zero.

## Limitations

- Synthetic data. The effect size, noise and costs are assumptions chosen for the study.
- One market path (one seed). The bootstrap interval covers sampling noise within it,
  not variation across markets.
- Costs are a flat rate per unit traded; there is no market impact, borrow cost or
  capacity limit.
- The sentiment model is represented by noisy readings of the true tone, not by
  AlphaDots' lexicon run on generated text.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args()

    results = _clean(run())
    if args.check:
        problems: list[str] = []
        if not RESULTS.exists():
            problems.append(f"{RESULTS.relative_to(ROOT)} is missing")
        else:
            committed = json.loads(RESULTS.read_text(encoding="utf-8"))
            problems += [f"results{p}" for p in _close(results, committed)][:10]
            if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != report(committed):
                problems.append(f"{REPORT.relative_to(ROOT)} does not match the committed results")
        for problem in problems:
            print(f"STALE {problem}: run `make research`", file=sys.stderr)
        return 1 if problems else 0

    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text(
        json.dumps(results, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    REPORT.write_text(report(results), encoding="utf-8", newline="\n")
    print(f"wrote {RESULTS.relative_to(ROOT)} and {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
